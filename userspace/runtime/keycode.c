char keyboard_get_ascii(uint8_t scancode, bool shift, bool caps_lock)
{
    if ((caps_lock || shift) && key_ascii[scancode][1]) {
        return key_ascii[scancode][1];
    }

    return key_ascii[scancode][0];
}
